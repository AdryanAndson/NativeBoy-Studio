// Build-time generator: writes the fallback/emulation interpreter from the shared
// opcode table (core/optable.cpp). Output: core/interp_gen.inc
#include "../core/optable.h"
#include <cstdio>
#include <string>

using namespace gb;

static std::string operands(const OpInfo& o, bool cb) {
    if (cb) return "";
    std::string s;
    if (o.len == 2) s = "const u8 n8 = rd(m, (u16)(pc + 1)); const s8 e8 = (s8)n8; (void)e8; (void)n8; ";
    if (o.len == 3) s = "const u16 n16 = rd16(m, (u16)(pc + 1)); (void)n16; ";
    return s;
}

int main(int argc, char** argv) {
    FILE* f = fopen(argc > 1 ? argv[1] : "interp_gen.inc", "w");
    if (!f) return 1;
    fprintf(f, "// GENERATED by tools/gen_interp.cpp from core/optable.cpp - do not edit\n");
    fprintf(f, "void interp_step(Machine& m) {\n  u16 pc = m.pc;\n  const u8 op = rd(m, pc);\n"
               "  if (GB_UNLIKELY(m.halt_bug)) { m.halt_bug = false; pc = (u16)(pc - 1); }  // HALT bug: the byte after HALT is read twice\n"
               "  switch (op) {\n");
    for (int op = 0; op < 256; op++) {
        const OpInfo& o = op_info((uint8_t)op);
        fprintf(f, "  case 0x%02X: { // %s\n    %s\n", op, o.mnem.c_str(), operands(o, false).c_str());
        int len = o.len;
        switch (o.kind) {
        case OK_NORMAL:
            if (op == 0xCB) {
                fprintf(f, "    const u8 cb = rd(m, (u16)(pc + 1)); m.pc = (u16)(pc + 2);\n    switch (cb) {\n");
                for (int c = 0; c < 256; c++) {
                    const OpInfo& q = cb_info((uint8_t)c);
                    fprintf(f, "    case 0x%02X: %s%s m.tick(%d); return;\n", c, q.pre ? ("m.tick(" + std::to_string(q.pre) + "); ").c_str() : "", q.code.c_str(), q.post);
                }
                fprintf(f, "    }\n    return;\n");
            } else {
                fprintf(f, "    m.pc = (u16)(pc + %d); %s%s m.tick(%d); return;\n", len, o.pre ? ("m.tick(" + std::to_string(o.pre) + "); ").c_str() : "", o.code.c_str(), o.post);
            }
            break;
        case OK_EI: case OK_DI:
            fprintf(f, "    m.pc = (u16)(pc + 1); %s m.tick(4); return;\n", o.code.c_str());
            break;
        case OK_STOP:
            fprintf(f, "    m.pc = (u16)(pc + 2); %s m.tick(4); return;\n", o.code.c_str());
            break;
        case OK_JP:
            fprintf(f, "    m.pc = n16; m.tick(%d); return;\n", o.cycles);
            break;
        case OK_JP_CC:
            fprintf(f, "    if (%s) { m.pc = n16; m.tick(%d); } else { m.pc = (u16)(pc + 3); m.tick(%d); } return;\n", o.cond.c_str(), o.cycles_taken, o.cycles);
            break;
        case OK_JR:
            fprintf(f, "    m.pc = (u16)(pc + 2 + e8); m.tick(%d); return;\n", o.cycles);
            break;
        case OK_JR_CC:
            fprintf(f, "    if (%s) { m.pc = (u16)(pc + 2 + e8); m.tick(%d); } else { m.pc = (u16)(pc + 2); m.tick(%d); } return;\n", o.cond.c_str(), o.cycles_taken, o.cycles);
            break;
        case OK_CALL:
            fprintf(f, "    push16(m, (u16)(pc + 3)); m.pc = n16; m.tick(%d); return;\n", o.cycles);
            break;
        case OK_CALL_CC:
            fprintf(f, "    if (%s) { push16(m, (u16)(pc + 3)); m.pc = n16; m.tick(%d); } else { m.pc = (u16)(pc + 3); m.tick(%d); } return;\n", o.cond.c_str(), o.cycles_taken, o.cycles);
            break;
        case OK_RET:
            fprintf(f, "    m.pc = pop16(m); m.tick(%d); return;\n", o.cycles);
            break;
        case OK_RET_CC:
            fprintf(f, "    if (%s) { m.pc = pop16(m); m.tick(%d); } else { m.pc = (u16)(pc + 1); m.tick(%d); } return;\n", o.cond.c_str(), o.cycles_taken, o.cycles);
            break;
        case OK_RETI:
            fprintf(f, "    m.pc = pop16(m); m.ime = true; m.ei_delay = 0; m.next_event = 0; m.tick(%d); return;\n", o.cycles);
            break;
        case OK_RST:
            fprintf(f, "    push16(m, (u16)(pc + 1)); m.pc = 0x%04X; m.tick(%d); return;\n", o.rst, o.cycles);
            break;
        case OK_JP_HL:
            fprintf(f, "    m.pc = HL; m.tick(4); return;\n");
            break;
        case OK_HALT:
            fprintf(f, "    m.pc = (u16)(pc + 1); if (m.ime || !(m.ie & m.iflag & 0x1F)) m.halted = true; else m.halt_bug = true; m.tick(4); return;\n");
            break;
        case OK_ILLEGAL:
            fprintf(f, "    m.locked = true; m.tick(4); return;\n");
            break;
        }
        fprintf(f, "  }\n");
    }
    fprintf(f, "  }\n}\n");
    fclose(f);
    return 0;
}
